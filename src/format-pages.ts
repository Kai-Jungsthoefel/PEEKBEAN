// The viewer's pages for single formats (dwg-viewer.html …), so that a search for "dwg viewer" finds the site. Plain
// data without browser code: the build reads it as well, to write the pages (vite.config.ts, prerender.ts). Each page
// says in its own words what the format is and what the viewer shows of it; pages that only swapped the format's name
// would count as doorway pages to search engines. So only formats people look for get one, and formats that share a
// page share a search (glTF and GLB, the camera raw formats).
import { PAIRS, type ConversionPair } from './convert/catalog';
import type { FormatCategory } from './core/types';

export interface FormatPage {
  /** Name in page addresses, e.g. "dwg" in dwg-viewer.html. */
  slug: string;
  /** The format as people search for it: "View DWG files.", "DWG viewer". */
  label: string;
  /** Title of the page when "<label> viewer" is not what people search for. */
  name?: string;
  /** What the files are, in the plural: "Your DWG drawings open on your computer …". */
  noun: string;
  category: FormatCategory;
  /** The page's conversions are those of files with these extensions (convert/catalog.ts). */
  extensions: string[];
  /** What the format is and where its files come from. */
  about: string;
  /** What the viewer shows of it and what one can do there. */
  features: string[];
  /** What the viewer does not show; left out when nothing is missing. */
  limits?: string;
}

