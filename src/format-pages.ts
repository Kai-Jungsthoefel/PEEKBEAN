export function findFormatPage(slug: string): FormatPage | undefined {
  return FORMAT_PAGES.find((page) => page.slug === slug);
}

/** File name of a format's page, relative to the site root. */
export const formatPagePath = (page: FormatPage) => `${page.slug}-viewer.html`;

export const formatPageName = (page: FormatPage) => page.name ?? `${page.label} viewer`;

/** Conversions of the format's files, those that search engines are meant to find. */
export function formatConversions(page: FormatPage): ConversionPair[] {
  return PAIRS.filter((pair) => pair.indexed && pair.source.extensions.some((extension) => page.extensions.includes(extension)));
}

/** The page of the format with one of these file extensions, if it has one. */
export function formatPageFor(extensions: string[]): FormatPage | undefined {
  return FORMAT_PAGES.find((page) => extensions.some((extension) => page.extensions.includes(extension)));
}
